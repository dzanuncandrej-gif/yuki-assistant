"""Пол ассистента следует за голосом.

Женским голосом Юки говорит «я нашла», мужским — «я нашёл». Раньше мужской
голос читал женские фразы: заготовки в коде («Открыла.», «Отправила…») и ответы
модели, которой в инструкциях написано «ты — живая девушка».

Два механизма:
• инструкции модели подменяются под мужской голос (`adapt`);
• любой текст перед синтезом проходит через `fix` — он переводит женские формы
  глаголов первого лица в мужские. Работает и на потоке: слово, разрезанное
  между кусками ответа, сначала собирается целиком (`stream_fix`).
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Iterator

# русские имена мужских голосов — так ассистент представляется
_NAMES = {"william": "Уильям", "remy": "Реми", "dmitry": "Дмитрий"}

# женская форма → мужская. Только глаголы и краткие прилагательные, которые
# ассистент говорит о себе; «была», «сама», «одна» не трогаем — они слишком
# часто относятся не к нему.
_WORDS: dict[str, str] = {}
for female in ["открыла", "закрыла", "нашла", "отправила", "сделала", "поставила", "включила", "выключила", "запустила", "напечатала", "нажала", "запомнила", "забыла", "удалила", "создала", "сохранила", "поняла", "прочитала", "посмотрела", "проверила", "скопировала", "вставила", "переключила", "свернула", "развернула", "вернула", "отменила", "смогла", "увидела", "заметила", "услышала", "записала", "скачала", "установила", "перезапустила", "отключила", "очистила", "передала", "написала", "ответила", "разобрала", "подумала", "нашла", "перенесла", "переместила", "переименовала", "начала", "закончила", "добавила", "убрала", "выбрала", "слышала", "видела", "знала", "думала", "хотела", "ждала", "готовила", "набрала", "позвонила", "напомнила", "собрала", "спросила", "искала", "попробовала", "успела", "справилась", "ошиблась", "разобралась", "поставила", "заблокировала", "разблокировала", "обновила", "подключила", "сбросила"]:
    _WORDS[female] = female[:-2] + "л" if not female.endswith("шла") else female[:-3] + "шёл"
_WORDS.update({
    "нашла": "нашёл", "пришла": "пришёл", "ушла": "ушёл", "зашла": "зашёл", "вошла": "вошёл",
    "перешла": "перешёл", "прошла": "прошёл", "смогла": "смог", "могла": "мог", "помогла": "помог",
    "легла": "лёг", "рада": "рад", "готова": "готов", "уверена": "уверен", "согласна": "согласен",
    "занята": "занят", "должна": "должен", "довольна": "доволен", "благодарна": "благодарен",
    "девушка-компаньон": "парень-компаньон",
    "скучала": "скучал", "соскучилась": "соскучился", "вернулась": "вернулся", "проснулась": "проснулся",
    "осталась": "остался", "старалась": "старался", "постаралась": "постарался", "рассказала": "рассказал",
    "показала": "показал", "объяснила": "объяснил", "решила": "решил", "посчитала": "посчитал",
    "вся внимание": "весь внимание",
})
_PATTERN = re.compile(r"\b(" + "|".join(sorted(map(re.escape, _WORDS), key=len, reverse=True)) + r")\b",
                      re.IGNORECASE)


def masculine() -> bool:
    """Звучит ли сейчас мужской голос."""
    try:
        from . import voices

        return voices.active().gender == "m"
    except Exception:
        return False


def name() -> str:
    try:
        from . import voices

        profile = voices.active()
    except Exception:
        return "Юки"
    return _NAMES.get(profile.key, "Юки") if profile.gender == "m" else "Юки"


def _replace(match: re.Match[str]) -> str:
    word = match.group(0)
    male = _WORDS.get(word.lower(), word)
    if word.isupper():
        return male.upper()
    if word[:1].isupper():
        return male[:1].upper() + male[1:]
    return male


def fix(text: str, male: bool | None = None) -> str:
    """Переводит женские формы первого лица в мужские, если голос мужской."""
    if not text or not (masculine() if male is None else male):
        return text
    return _PATTERN.sub(_replace, text)


def stream_fix(pieces: Iterable[str]) -> Iterator[str]:
    """То же для потока: отдаёт текст только целыми словами."""
    male = masculine()
    if not male:
        yield from pieces
        return
    buffer = ""
    for piece in pieces:
        buffer += piece
        cut = max(buffer.rfind(" "), buffer.rfind("\n"))
        if cut <= 0:
            continue
        ready, buffer = buffer[: cut + 1], buffer[cut + 1:]
        yield fix(ready, True)
    if buffer:
        yield fix(buffer, True)


def adapt(prompt: str) -> str:
    """Инструкции модели под текущий голос: мужской — говорит о себе как мужчина."""
    if not masculine():
        return prompt
    who = name()
    text = prompt.replace("Ты — Юки: живая девушка-компаньон", f"Ты — {who}: живой парень-компаньон")
    text = text.replace("Ты — Юки, живая девушка-компаньон", f"Ты — {who}, живой парень-компаньон")
    text = text.replace("Ты — Юки", f"Ты — {who}")
    text = text.replace("девушка-компаньон", "парень-компаньон").replace("которая живёт", "который живёт")
    text = fix(text, True)  # примеры в инструкциях («Открыла, держи») — тоже в мужском роде
    return text + (
        f"\n\nВАЖНО: сейчас ты говоришь мужским голосом, тебя зовут {who} (на имя «Юки» ты тоже "
        "откликаешься). О себе говори только в мужском роде: «я нашёл», «я сделал», «я рад», "
        "«я готов». Женские формы о себе запрещены."
    )
