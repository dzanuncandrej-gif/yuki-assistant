from __future__ import annotations

LOGIC = """Файл логики:
— Только чистые функции и классы, никакого tkinter, print и input: так его можно проверить тестами.
— Ошибки ввода — понятные исключения (ValueError с текстом по-русски), а не падения.
— Короткие функции с говорящими именами, аннотации типов, докстринг в одну строку у публичных функций.
— Состояние игры/приложения — в одном классе с методами (step, reset, ...), без глобальных переменных.
— Компактно: до 120 строк. Логика считает и хранит, но не форматирует текст для экрана."""

TESTS = """Файл тестов:
— Только стандартный unittest: import unittest, класс Test...(unittest.TestCase), в конце if __name__ == "__main__": unittest.main().
— Импортируй логику по имени модуля (from logic import ...), не из main.py.
— 6–8 тестов на главное поведение: результаты вычислений и правила, крайние случаи (ноль, пусто, граница поля).
— Проверяй ровно то, что делает код логики выше: читай его, а не угадывай. assertRaises — только если функция
  действительно выбрасывает это исключение.
— Не проверяй форматирование строк для экрана и порядок вызовов — только результаты."""

GUI = """Окно на tkinter:
— Тёмная тема константами в начале: BG="#11131a", PANEL="#1b1f2a", ACCENT="#5b8cff", TEXT="#e8ecf4", MUTED="#8a93a6"; шрифт ("Segoe UI", 12).
— Только tk.* виджеты для цвета (у ttk нет bg/fg); кнопки relief="flat", bd=0, cursor="hand2", activebackground, отступы padx/pady.
— Наведение: bind("<Enter>")/("<Leave>") меняет цвет кнопки.
— Сетка grid с weight у строк и столбцов, root.minsize(...), окно по центру экрана.
— Клавиатура дублирует мышь: root.bind("<Key>", ...), Enter, Escape, BackSpace.
— Логика — только через модуль логики; ошибки показывай в окне (метка статуса), не падай.
— Класс App(tk.Tk) или App с root; в конце if __name__ == "__main__": App().mainloop() (или root.mainloop())."""

GAME = """Игра на tkinter Canvas:
— Состояния: меню → игра → пауза (P) → конец (экран со счётом, R — заново). Всё в одном классе.
— Цикл только через self.after(ms, self.tick), никаких while True и time.sleep.
— Управление стрелками и WASD, пробел — старт/пауза; запрет разворота на 180° там, где это важно.
— Счёт и рекорд на экране; рекорд хранится в JSON рядом с файлом (Path(__file__).with_name("record.json")).
— Тёмный фон, яркие фигуры, сетка клеток константой CELL; скорость растёт со счётом.
— Правила (движение, столкновения, очки) — в модуле логики, окно только рисует состояние."""

CONSOLE = """Консольная программа:
— Меню с номерами действий, цикл до команды «0»/«выход»; понятные подсказки на русском.
— Любой ввод проверяется: неверный — сообщение и повтор, а не падение; EOFError и KeyboardInterrupt — вежливый выход.
— Данные, которые стоит сохранить, — в JSON рядом с файлом.
— Логика в отдельном модуле; в main.py только ввод/вывод и def main(), вызов в if __name__ == "__main__"."""

WEB = """Сайт без сборщиков и CDN:
— index.html: семантика (header, main, section, footer), <meta name="viewport">, подключение style.css и script.js (defer).
— style.css: переменные в :root (--bg:#0d0f14; --panel:#161a22; --accent:#6d8bff; --text:#e9edf5), шрифт system-ui,
  flex/grid, адаптивность (@media max-width:700px), плавные transition, скругления, тени, состояние :hover и :focus-visible.
— script.js: без глобального мусора (всё в функциях), обработчики через addEventListener, данные — в localStorage,
  проверка ввода, никакого alert — сообщения выводятся в элемент на странице.
— id и классы в script.js и style.css должны точно совпадать с разметкой index.html."""

_BY_KIND = {"gui": GUI, "game": GAME, "console": CONSOLE, "web": WEB}


def for_file(kind: str, path: str, entry: str) -> str:
    """Руководство для конкретного файла проекта."""
    name = path.rsplit("/", 1)[-1]
    if name.startswith("test_"):
        return TESTS
    if kind == "web":
        return WEB
    if path != entry and path.endswith(".py"):
        return LOGIC
    return _BY_KIND.get(kind, GUI)
