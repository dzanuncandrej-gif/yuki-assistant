"""Узнаёт вопросы о фактах мира — на них отвечают по свежему поиску, а не по памяти модели.

Семимиллиардная модель помнит мир на момент обучения и уверенно выдумывает
остальное: цену биткоина, возраст знаменитости, дату выхода фильма. Раньше такие
вопросы попадали в разговорный путь без инструментов — отсюда «бред». Теперь
вопрос о фактах сначала уходит в поиск, и модель пересказывает найденное.
"""

from __future__ import annotations

import re

_LEAD = r"^(?:(?:а|и|ну|слушай|скажи|подскажи|юки|кстати|интересно)[\s,]+)*"

_FACT_QUESTION = re.compile(
    _LEAD
    + r"(?:"
    r"кто\s+(?:такой|такая|такие|такое|был|была|были|сейчас|является|придумал|изобрёл|изобрел|"
    r"написал|снял|спел|поёт|поет|выиграл|победил|основал|создал|играет)|"
    r"что\s+(?:такое|значит|означает|известно|случилось|произошло|сейчас\s+(?:в|с|у)|нового\s+(?:у|в|про|с))|"
    r"сколько\s+(?:стоит|стоят|стоил|стоила|лет|весит|живут|длится|идёт|идет|людей|человек|"
    r"километров|калорий|серий|сезонов|зарабатывает|получает)|"
    r"какой\s+(?:сейчас\s+)?(?:курс|год\s+(?:выхода|основания)|рост|возраст|рейтинг)|"
    r"(?:курс|цена|стоимость)\s+\w+|"
    r"когда\s+(?:выйдет|вышел|вышла|вышло|выходит|будет|был|была|было|родился|родилась|умер|умерла|"
    r"начнётся|начнется|закончится|открывается|основан)|"
    r"где\s+(?:находится|живёт|живет|купить|родился|родилась|снимали|производят)|"
    r"(?:почему|зачем|отчего)\s+(?!ты\b|тебе\b|тебя\b)|"
    r"как\s+(?:сделать|приготовить|работает|называется|переводится|решить|научиться|установить|"
    r"починить|исправить|вылечить|избавиться|заработать|правильно|пишется|играть\s+в)|"
    r"(?:найди|поищи|погугли|загугли|пробей)\s+(?:в\s+интернете\s+|в\s+сети\s+|в\s+гугле\s+)?"
    r"(?:информацию|инфу|что|кто|как|сколько|где|когда|про|о|об)|"
    r"(?:найди|поищи)\s+в\s+(?:интернете|сети|гугле)|"
    r"(?:расскажи|рассказать)\s+(?:мне\s+)?(?:про|о|об)\s+(?!себ|тебе|вас\b)|"
    r"что\s+ты\s+знаешь\s+(?:о|об|про)\s+(?!себ|мне|меня)|"
    r"(?:последние\s+)?новости\s+(?:про|о|об|по)\s+"
    r")",
    re.IGNORECASE,
)

# вопросы о ней самой и о человеке — разговор, поиск тут не поможет
_PERSONAL = re.compile(r"\b(?:ты|тебя|тебе|твой|твоя|твоё|твои|меня|мне|мой|моя|моё|мои)\b", re.IGNORECASE)

_STRIP = re.compile(
    _LEAD + r"(?:(?:найди|поищи|погугли|загугли|пробей)\s+(?:в\s+(?:интернете|сети|гугле)\s+)?"
    r"(?:информацию\s+|инфу\s+)?(?:про\s+|о\s+|об\s+)?|(?:расскажи|рассказать)\s+(?:мне\s+)?"
    r"(?:про|о|об)\s+|что\s+ты\s+знаешь\s+(?:о|об|про)\s+)",
    re.IGNORECASE,
)


def web_query(text: str) -> str | None:
    """Поисковый запрос, если фраза — вопрос о фактах мира. Иначе None."""
    clean = (text or "").strip(" ?!.")
    if len(clean) < 6 or not _FACT_QUESTION.search(clean):
        return None
    # «почему ты молчишь», «расскажи о себе» — не к поисковику
    if _PERSONAL.search(clean) and not re.search(r"\b(?:курс|цена|стоит|новости)\b", clean, re.I):
        return None
    query = _STRIP.sub("", clean).strip(" ,")
    return query or clean


# Просьбы, на которые нужен развёрнутый ответ, а не одна фраза вслух: объяснить,
# разобрать, сравнить, написать код или план. Такой ответ показывается на экране
# целиком, а вслух звучит только суть — длинный монолог никто не дослушает.
_DEEP_REQUEST = re.compile(
    _LEAD
    + r"(?:.*\b(?:подробн\w*|детальн\w*|развёрнут\w*|развернут\w*|пошагов\w*|по\s+шагам|по\s+пунктам|"
    r"в\s+деталях|плюсы\s+и\s+минусы|за\s+и\s+против)\b|"
    r"(?:объясни|разбери|распиши|растолкуй|проанализируй|сравни|сопоставь)\b|"
    r"(?:в\s+ч[её]м|какая)\s+разница|"
    r"(?:напиши|сделай|создай|составь|сгенерируй)\s+(?:мне\s+)?(?:\w+\s+)?"
    r"(?:код\w*|скрипт\w*|функци\w*|программ\w*|класс\w*|запрос\w*|регулярк\w*|план\w*|"
    r"конспект\w*|эссе|сочинени\w*|стать\w*|резюме|инструкци\w*|чек-?лист\w*|таблиц\w*|"
    r"расписани\w*|список\s+(?:идей|дел|покупок|шагов)|пост\w*|рецепт\w*|программу\s+тренировок)|"
    r"(?:придумай|предложи)\s+(?:\w+\s+)?(?:иде\w*|вариант\w*|план\w*|назван\w*|сюжет\w*)|"
    r"помоги\s+(?:мне\s+)?(?:разобраться|понять|написать|составить|спланировать|выбрать)|"
    r"(?:что|какой|какая|какое|какие)\s+лучше\b|посоветуй|дай\s+(?:совет|рекомендаци\w*)|"
    r"как\s+(?:устроен\w*|работает|научиться|выучить|подготовиться|спланировать)\b"
    r")",
    re.IGNORECASE,
)

# Короткие приказы с теми же словами: «подробнее громкость» не бывает, а вот
# «открой подробно настройки» — приказ. Глагол действия перевешивает.
_COMMAND_LEAD = re.compile(
    _LEAD + r"(?:открой|закрой|включи|выключи|запусти|поставь|сделай\s+(?:громче|тише|скриншот)|"
    r"отправь|напиши\s+(?!(?:мне\s+)?(?:\w+\s+)?(?:код|скрипт|функци|программ|класс|план|эссе|"
    r"сочинени|стать|резюме|инструкци|конспект|пост|рецепт|таблиц|расписани|список))|"
    r"найди\s+(?:файл|папку|окно)|громкость|яркость)",
    re.IGNORECASE,
)


def deep_request(text: str) -> bool:
    """True, если просят подробный ответ: объяснение, разбор, код, план, совет."""
    clean = (text or "").strip()
    if len(clean) < 8 or _COMMAND_LEAD.search(clean):
        return False
    return bool(_DEEP_REQUEST.search(clean))


# «что скажешь об этом исполнителе», «кто это поёт», «что за песня играет»
_ABOUT_PLAYING = re.compile(
    r"(?P<artist>(?:эт(?:от|ого|ом|им|у|ой|а)|данн\w+)\s+(?:исполнител\w*|певц\w*|певиц\w*|артист\w*|музыкант\w*|"
    r"рэпер\w*|групп\w*|автор\w*|диджее?\w*))|"
    r"(?P<song>(?:эт(?:а|ой|у|от|ом|ого)|данн\w+)\s+(?:песн\w*|трек\w*|композици\w*|мелоди\w*))|"
    r"(?P<what>кто\s+(?:это\s+)?(?:поёт|поет|исполняет|играет)|что\s+(?:сейчас\s+|это\s+)?(?:играет|звучит)|"
    r"что\s+за\s+(?:песня|трек|музыка|композиция))",
    re.IGNORECASE,
)


def about_playing(text: str) -> str | None:
    """Вопрос о том, что сейчас играет: 'artist', 'song', 'what' или None."""
    match = _ABOUT_PLAYING.search(text or "")
    if match is None:
        return None
    if match.group("what"):
        # «кто поёт» и «что играет» — короткий ответ, но «расскажи о…» — уже рассказ
        return "artist" if re.search(r"расскаж|скажешь|знаешь|кто\s+так", text, re.I) else "what"
    return "song" if match.group("song") else "artist"
