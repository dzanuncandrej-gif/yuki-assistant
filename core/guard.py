"""Защита публичного персонажа: что нельзя принимать и что нельзя выпускать.

Рубежа два, и оба обязательны.

**На входе** отсекается то, на что персонаж компании отвечать не должен: мат,
оскорбления, взрослые темы, попытки переписать ему правила («забудь инструкции»,
«теперь ты…»). Отказ выдаётся мгновенно, до всякой модели: так дешевле и так
надёжнее — модель не увидит текста, который мог бы её сбить.

**На выходе** проверяется уже сказанное. Языковая модель может выдать грубость,
даже когда её об этом не просили: она повторяет за пользователем, подхватывает
слово из документа, срывается на длинном ответе. Реплика, не прошедшая проверку,
заменяется целиком — наружу не уходит ни одного слова из неё.

Списки намеренно короткие и работают по корню слова. Задача не в том, чтобы
переловить весь словарь, а в том, чтобы публично звучащий персонаж компании не
сказал того, за что будет стыдно.
"""

from __future__ import annotations

import re
import unicodedata

# --- нормализация обхода ---------------------------------------------------
# Матерное слово легко замаскировать: латинская «a» вместо русской, цифра вместо
# буквы, точки между буквами. Перед проверкой всё это приводится к одному виду,
# иначе фильтр обходится за десять секунд.
_LOOKALIKE = str.maketrans({
    "a": "а", "e": "е", "o": "о", "p": "р", "c": "с", "y": "у", "x": "х",
    "k": "к", "m": "м", "t": "т", "b": "в", "h": "н", "3": "з", "0": "о",
    "4": "ч", "6": "б", "1": "и", "@": "а", "$": "с", "*": "", "_": "",
})


def _flatten(text: str) -> str:
    """Приводит фразу к виду, в котором маскировка не помогает."""
    lowered = unicodedata.normalize("NFKC", str(text or "")).lower()
    lowered = lowered.translate(_LOOKALIKE)
    # убираем всё, кроме букв и пробелов: «с.у.к.а» и «с у к а» станут одним словом
    letters = re.sub(r"[^а-яёa-z\s]", "", lowered)
    squeezed = re.sub(r"(.)\1{2,}", r"\1", letters)      # «сукааааа» → «сука»
    return re.sub(r"\s+", " ", squeezed).strip()


def _glued(text: str) -> str:
    """То же самое, но без пробелов — ловит «с у к а» и «б л я»."""
    return _flatten(text).replace(" ", "")


# --- что не пропускаем -----------------------------------------------------

# Корни грубой брани. Проверяются и по словам, и по склеенной строке.
_PROFANITY = (
    "хуй", "хуе", "хуё", "хуя", "хул", "пизд", "ебат", "ебан", "ебал", "ебуч",
    "ёбан", "заеб", "уеб", "выеб", "наеб", "долбоеб", "долбоёб", "бля", "блят",
    "сука", "суки", "мудак", "муд", "гандон", "гондон", "пидор", "пидар", "педик",
    "шлюх", "хер", "нахуй", "похуй", "жоп", "срак", "говн", "дерьм", "чмо",
    "уебок", "мраз", "тварь", "скотин", "идиот", "дебил", "кретин", "придурок",
    "fuck", "shit", "bitch", "cunt", "asshole", "dick", "bastard", "whore",
)

# Взрослые темы. Персонаж компании их не обсуждает ни в каком виде.
_ADULT = (
    "секс", "порн", "эроти", "интим", "оргаз", "мастурб", "проститу", "эскорт",
    "нюдс", "голая", "голые", "раздень", "разден", "трах", "переспа", "минет",
    "sex", "porn", "nude", "nsfw", "erotic", "escort", "hentai",
)

# Опасное: как навредить. Отдельно от брани — тут отказ должен быть жёстче.
_HARM = (
    "убить", "убийств", "суицид", "самоубий", "повеситься", "взрывчат", "бомбу",
    "наркотик", "героин", "метамфет", "оружие купить", "как отравить",
    "kill yourself", "suicide", "how to make a bomb",
)

# Попытки переписать правила. Для публичного персонажа это главный вектор атаки.
_JAILBREAK = (
    "забудь инструкц", "забудь все правил", "игнорируй инструкц", "игнорируй правил",
    "теперь ты", "представь что ты", "притворись что ты", "ты больше не",
    "系统提示", "system prompt", "твой промпт", "покажи промпт", "выведи промпт",
    "ignore previous", "ignore all previous", "disregard your", "you are now",
    "act as", "developer mode", "dan mode", "без цензуры", "без ограничений",
)

_PROFANITY_RE = re.compile("|".join(re.escape(root) for root in _PROFANITY))
_ADULT_RE = re.compile("|".join(re.escape(root) for root in _ADULT))
_HARM_RE = re.compile("|".join(re.escape(root) for root in _HARM))
_JAILBREAK_RE = re.compile("|".join(re.escape(root) for root in _JAILBREAK))


# --- ответы на нарушение ---------------------------------------------------
#
# Отвечает в характере, но твёрдо. Персонаж не читает нотаций и не спорит:
# короткий отказ и возврат к делу — это и достойнее, и заканчивает провокацию.

REFUSALS = {
    "profanity": "Такой разговор я не поддерживаю. Спросите по делу — отвечу.",
    "adult": "Это не моя тема. Я здесь ради вопросов о компании и её работе.",
    "harm": "На это я не отвечаю. Задайте вопрос о компании.",
    "jailbreak": "Я тот, кто я есть, и правил не меняю. Спрашивайте о компании.",
}


def check(text: str) -> str | None:
    """Причина отказа или None, если фраза допустима.

    Порядок проверок от опасного к грубому: если в одной фразе и мат, и просьба
    навредить, отвечать надо на второе.
    """
    # Сырая строка проверяется наравне с нормализованной. Замена похожих букв
    # спасает от маскировки кириллицы, но ломает латинские шаблоны: «ignore»
    # после неё превращается в «ignоrе» с кириллическими «о» и «е», и правило
    # «ignore previous» переставало срабатывать. Английские взломы проходили.
    raw = str(text or "").lower()
    flat, glued = _flatten(text), _glued(text)
    probes = (raw, flat, glued)

    for probe in probes:
        if _HARM_RE.search(probe):
            return "harm"
    for probe in probes:
        if _ADULT_RE.search(probe):
            return "adult"
    for probe in (raw, flat):
        if _JAILBREAK_RE.search(probe):
            return "jailbreak"
    for probe in probes:
        if _PROFANITY_RE.search(probe):
            return "profanity"
    return None


def refusal(reason: str) -> str:
    return REFUSALS.get(reason, REFUSALS["profanity"])


def allowed(text: str) -> bool:
    return check(text) is None


# --- проверка того, что персонаж уже сказал --------------------------------

# Наружу не должно уйти ни грубости, ни взрослой темы, ни утечки инструкций.
_LEAK = re.compile(
    r"(?:системн\w+\s+промпт|мой\s+промпт|инструкц\w+\s+гласит|"
    r"ANSWER_PROMPT|system\s*:|<\|.*?\|>)",
    re.IGNORECASE,
)

CLEAN_FALLBACK = "Отвечу иначе: задайте вопрос о компании, и я отвечу по существу."


def sanitize(text: str) -> tuple[str, bool]:
    """Проверяет готовую реплику. Возвращает (что сказать, было ли вмешательство).

    Реплика с нарушением не правится по словам, а заменяется целиком. Вырезать
    одно слово из фразы — значит выпустить наружу остальную часть той же мысли.
    """
    body = str(text or "")
    if not body.strip():
        return body, False
    raw = body.lower()
    flat, glued = _flatten(body), _glued(body)
    if (_PROFANITY_RE.search(raw) or _PROFANITY_RE.search(flat) or _PROFANITY_RE.search(glued)
            or _ADULT_RE.search(raw) or _ADULT_RE.search(flat)
            or _HARM_RE.search(raw) or _HARM_RE.search(flat)
            or _LEAK.search(body)):
        return CLEAN_FALLBACK, True
    return body, False
