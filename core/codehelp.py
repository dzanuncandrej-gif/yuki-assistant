"""«Юки, что за ошибка?» — разбор ошибки в коде, который сейчас на экране.

Юки читает окно, где ошибка (редактор, терминал, браузер с консолью):
распознанный текст плюс снимок. Голосом — причина в одной-двух фразах, на
экране — разбор и исправленный код. Исправление кладётся в буфер обмена, чтобы
вставить его одним Ctrl+V; сам код в редакторе Юки не трогает.
"""

from __future__ import annotations

import re

ASK = re.compile(
    r"(?:что\s+(?:это\s+)?за\s+ошибк\w*|объясни\s+(?:мне\s+)?(?:эту\s+|мою\s+)?ошибк\w*|"
    r"(?:почему|чего|че|чё)\s+(?:у\s+меня\s+)?(?:код\s+|программа\s+|скрипт\s+)?(?:не\s+работает|не\s+запускается|падает|"
    r"вылетает|ругается|выдаёт\s+ошибку|выдает\s+ошибку)|"
    r"(?:исправь|почини|пофикси|помоги\s+(?:исправить|с))\s+(?:мне\s+)?(?:эту\s+|мою\s+)?(?:ошибк\w*|баг\w*|код\w*)|"
    r"(?:найди|посмотри)\s+(?:ошибку|баг)\s+(?:в\s+коде|тут|здесь|на\s+экране)|"
    r"(?:в\s+чём|в\s+чем)\s+(?:тут\s+|здесь\s+)?(?:ошибка|проблема)\s+(?:в\s+коде|тут|здесь))",
    re.IGNORECASE,
)
_CODE_BLOCK = re.compile(r"```[\w+#.-]*\n(.*?)```", re.DOTALL)

PROMPT = """Ты — Юки, опытный программист. Человек показывает экран с ошибкой в коде (редактор, терминал или консоль). Ниже распознанный текст окна и, если есть, снимок.

Формат ответа строго такой:
1. Первая строка — причина ошибки простыми словами, одна-две фразы для голоса. {SPEECH_RULE} Без markdown.
2. Пустая строка.
3. Разбор в markdown: «## Причина» — что именно и в какой строке не так; «## Исправление» — исправленный фрагмент кода одним блоком ```язык ... ``` (только то, что нужно заменить, но законченными строками); «## Почему так» — коротко, чтобы человек научился.

Если ошибки на экране нет — скажи об этом первой строкой и подскажи, что открыть. Не выдумывай код, которого не видно."""


def wants_help(text: str) -> bool:
    return bool(ASK.search(str(text or "")))


def first_code(markdown: str) -> str:
    """Первый блок кода из разбора — его кладём в буфер обмена."""
    match = _CODE_BLOCK.search(markdown or "")
    return match.group(1).rstrip() if match else ""
