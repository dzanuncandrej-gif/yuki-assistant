MAX_TOOLS = 20


def select(text: str, limit: int = MAX_TOOLS) -> list[dict[str, Any]]:
    """Схемы инструментов, подходящих под фразу. Порядок: базовые, затем совпавшие."""
    query = (text or "").lower()
    if not query.strip():
        return specs()

    chosen: list[str] = [name for name in CORE]
    scored: list[tuple[int, str]] = []
    for item in catalog():
        if item.name in chosen:
            continue
        words = KEYWORDS.get(item.name, ())
        hits = sum(1 for word in words if word in query)
        if hits:
            scored.append((hits, item.name))

    for _, name in sorted(scored, key=lambda pair: -pair[0]):
        if len(chosen) >= limit:
            break
        chosen.append(name)

    known = {item.name: item for item in catalog()}
    return [known[name].spec() for name in chosen if name in known]
