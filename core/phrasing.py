"""Приведение живого вопроса к виду, который переживёт поиск по смыслу.

Посетитель сайта пишет быстро и небрежно. Он ошибается в раскладке, глотает
буквы, пишет «скока», «че», «прайс» и «что по бабкам». Векторный поиск такое
терпит плохо: опечатка меняет токены, и близость проседает ровно там, где вопрос
задан живее всего.

Четыре правки, по возрастанию цены:

1. **Раскладка.** «crjkmrj» — это «сколько», набранное не в той раскладке.
   Правится однозначно и мгновенно, без всякой модели.
2. **Сленг и сокращения.** Короткий словарь: «скока» → «сколько», «прайс» → «цена».
3. **Опечатки.** Слово, которого нет в базе, сверяется по похожести со словарём
   самой базы знаний — не с языком вообще, а с теми словами, что в документах есть.
4. **Сжатие.** У длинного вопроса выделяется смысловое ядро: многословная рамка
   размывает вектор и уводит поиск не туда.

Исходную фразу не выбрасываем. Модель отвечает по ней — там сохранилась интонация
вопроса; выправленная версия нужна только поиску.
"""

from __future__ import annotations

import difflib
import re
from functools import lru_cache

# --- раскладка -------------------------------------------------------------

_EN = "qwertyuiop[]asdfghjkl;'zxcvbnm,.`QWERTYUIOP{}ASDFGHJKL:\"ZXCVBNM<>~"
_RU = "йцукенгшщзхъфывапролджэячсмитьбюёЙЦУКЕНГШЩЗХЪФЫВАПРОЛДЖЭЯЧСМИТЬБЮЁ"
_TO_RU = str.maketrans(_EN, _RU)

_LATIN_WORD = re.compile(r"^[a-z\[\];',.`]+$", re.IGNORECASE)
_WORD = re.compile(r"[а-яёa-z]+", re.IGNORECASE)

# слова, которые встречаются в любом вопросе и в базу знаний не попадают
_COMMON = frozenset({
    "сколько", "какой", "какая", "какие", "что", "как", "где", "когда", "почему",
    "кто", "чем", "зачем", "стоит", "цена", "можно", "есть", "работа", "работает",
    "ваша", "ваши", "вы", "мне", "нам", "это", "для", "про", "или", "если",
})


def fix_layout(text: str, character: str = "") -> str:
    """«crjkmrj» → «сколько». Трогает только слова целиком на латинице.

    Проверка по гласным оказалась негодной: «Lean Production» после перевода тоже
    состоит из гласных и согласных, и превращалось в «Дуфт Зкщвгсешщт». Поэтому
    перевод принимается, только если получившееся слово встречается в базе знаний.
    Английские названия — Lean, LMS, Kaizen — остаются как есть.
    """
    fixed: list[str] = []
    for word in text.split():
        core = word.strip(".,!?;:()«»\"'")
        if len(core) < 3 or not _LATIN_WORD.match(core):
            fixed.append(word)
            continue
        candidate = core.translate(_TO_RU)
        if _plausible(candidate, character):
            fixed.append(word.replace(core, candidate))
        else:
            fixed.append(word)
    return " ".join(fixed)


def _plausible(word: str, character: str) -> bool:
    """Похоже ли слово на настоящее слово из этой предметной области."""
    low = word.lower()
    if low in _COMMON:
        return True
    stems = _stems(character) if character else frozenset()
    if not stems:
        vowels = sum(1 for char in low if char in "аеёиоуыэюя")
        return 1 <= vowels <= len(low) - 1
    return low[:5] in stems


# --- сленг и сокращения ----------------------------------------------------

_SLANG: dict[str, str] = {
    "скока": "сколько", "скок": "сколько", "скоко": "сколько",
    "че": "что", "чё": "что", "чо": "что", "шо": "что",
    "прайс": "цена", "прайслист": "цена", "ценник": "цена",
    "бабки": "деньги", "бабок": "денег", "бабло": "деньги", "лям": "миллион",
    "косарь": "тысяча", "косарей": "тысяч",
    "норм": "нормально", "спс": "спасибо", "плз": "пожалуйста", "пжлст": "пожалуйста",
    "инфа": "информация", "инфу": "информацию", "инфо": "информация",
    "прив": "привет", "здарова": "привет", "хай": "привет", "ку": "привет",
    "оч": "очень", "кст": "кстати", "имхо": "по-моему",
    "тел": "телефон", "мыло": "почта",
    "фирма": "компания", "контора": "компания", "конторе": "компании",
    "работник": "сотрудник", "тренинг": "обучение",
    "почем": "сколько стоит", "почём": "сколько стоит",
}

_SLANG_PHRASES: tuple[tuple[str, str], ...] = (
    ("чем вы занимаетесь", "какие услуги"),
    ("чем занимаетесь", "какие услуги"),
    ("что по деньгам", "сколько стоит"),
    ("что по бабкам", "сколько стоит"),
)


def expand_slang(text: str) -> str:
    """Заменяет разговорные формы на словарные. Только целыми словами."""
    result = text
    lowered = result.lower()
    for phrase, plain in _SLANG_PHRASES:
        if phrase in lowered:
            result = re.sub(re.escape(phrase), plain, result, flags=re.IGNORECASE)
            lowered = result.lower()

    def swap(match: re.Match[str]) -> str:
        return _SLANG.get(match.group(0).lower(), match.group(0))

    return _WORD.sub(swap, result)


# --- опечатки --------------------------------------------------------------


@lru_cache(maxsize=8)
def _vocabulary(character: str) -> tuple[str, ...]:
    """Слова, которые реально встречаются в базе знаний этого персонажа.

    Исправлять опечатки по словарю языка бессмысленно: «хаттацу», «кайдзен» и
    «бусидо» ни в одном словаре не найдутся, а именно их и пишут с ошибками.
    """
    from . import knowledge

    base = knowledge.load(character)
    if base is None:
        return ()
    seen: dict[str, int] = {}
    for chunk in base.texts:
        for word in _WORD.findall(chunk.lower()):
            if len(word) >= 4:
                seen[word] = seen.get(word, 0) + 1
    return tuple(sorted(seen, key=lambda item: -seen[item])[:4000])


@lru_cache(maxsize=8)
def _stems(character: str) -> frozenset[str]:
    """Первые пять букв каждого слова базы. По ним видно, что слово «своё»."""
    return frozenset(word[:5] for word in _vocabulary(character) if len(word) >= 5)


def fix_typos(text: str, character: str, cutoff: float = 0.86) -> str:
    """Правит слова, похожие на слова из базы, но написанные с ошибкой.

    Осторожность здесь важнее полноты. Более смелая версия портила правильные
    слова: «работа» превращалась в «работ», «эффективность» — в «эффективности»,
    потому что именно эти формы чаще встречаются в документах. Поэтому слово, чья
    основа уже есть в базе, не трогается вовсе: это не опечатка, а другая падежная
    форма, и поиск по смыслу с ней справится сам.
    """
    words = _vocabulary(character)
    if not words:
        return text
    known, stems = set(words), _stems(character)

    def repair(match: re.Match[str]) -> str:
        word = match.group(0)
        low = word.lower()
        if len(low) < 5 or low in known or low in _SLANG or low in _COMMON:
            return word
        if low[:5] in stems:
            return word
        close = difflib.get_close_matches(low, words, n=1, cutoff=cutoff)
        if not close:
            return word
        fixed = close[0]
        if len(fixed) < len(low) - 1:
            return word
        return fixed.capitalize() if word[0].isupper() else fixed

    return _WORD.sub(repair, text)


# --- сжатие многословного вопроса ------------------------------------------

# Вежливая рамка вокруг сути. Для человека это нормальная речь, для векторного
# поиска — шум, который тянет вектор в сторону от нужного абзаца.
_FRAMING = frozenset({
    "сравни", "сравните", "сравнение", "объясни", "объясните", "поясни", "поясните",
    "расскажи", "расскажите", "опиши", "опишите", "подробно", "подробнее",
    "развёрнуто", "развернуто", "пожалуйста", "можешь", "можете", "интересно",
    "скажи", "скажите", "подскажи", "подскажите", "отличаются", "отличается",
    "разница", "кратко", "вкратце", "хотел", "хотела", "хотелось", "именно",
    "также", "вообще", "конкретно", "например",
})

_NOISE = frozenset({
    "а", "и", "но", "или", "же", "ли", "бы", "то", "это", "как", "что", "чем",
    "они", "он", "она", "оно", "мне", "вы", "ваши", "ваша", "ваш", "их", "его",
    "у", "в", "на", "по", "с", "о", "об", "для", "от", "до", "за", "из", "при",
    "так", "там", "тут", "вот", "уже", "ещё", "еще", "мы", "нас", "нам",
})


def condense(text: str) -> str:
    """Оставляет от вопроса смысловое ядро.

    Нужно длинным вопросам. «Сравни ваши направления и объясни подробно, чем они
    отличаются» — по смыслу это «направления». Вектор полной фразы уезжал к
    отзывам, вектор ядра попадает точно в нужный абзац.

    Отбор идёт по множествам слов, а не регулярным выражением: длинное
    чередование с кириллицей легко испортить при правке, и оно однажды уже
    перестало срабатывать молча, оставив функцию бесполезной.
    """
    words = [
        word for word in _WORD.findall(str(text or ""))
        if word.lower() not in _FRAMING
        and word.lower() not in _NOISE
        and len(word) > 2
    ]
    core = " ".join(words[:8])
    return core or str(text or "").strip()


def normalize(text: str, character: str = "") -> str:
    """Полная подготовка вопроса к поиску: раскладка, сленг, опечатки."""
    stage = fix_layout(str(text or "").strip(), character)
    stage = expand_slang(stage)
    if character:
        stage = fix_typos(stage, character)
    return re.sub(r"\s+", " ", stage).strip()


def forget(character: str = "") -> None:
    """Сбрасывает словарь: база знаний пересобрана, слова могли измениться."""
    _vocabulary.cache_clear()
    _stems.cache_clear()
